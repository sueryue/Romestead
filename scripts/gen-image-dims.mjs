// One-off: measure every image under public/media and emit src/content/image-dims.ts
// so templates can set width/height (prevents CLS).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const mediaRoot = path.join(root, 'public/media');

const entries = [];
for (const dir of ['screens', 'logos']) {
  const d = path.join(mediaRoot, dir);
  if (!fs.existsSync(d)) continue;
  for (const f of fs.readdirSync(d)) {
    const full = path.join(d, f);
    try {
      const meta = await sharp(full).metadata();
      entries.push({ src: `${dir}/${f}`, w: meta.width, h: meta.height });
    } catch {
      console.log(`skip ${f}`);
    }
  }
}

const lines = entries
  .sort((a, b) => a.src.localeCompare(b.src))
  .map((e) => `  '${e.src}': { width: ${e.w}, height: ${e.h} },`);

const out = `// Generated by scripts/gen-image-dims.mjs — do not edit by hand.
// Intrinsic pixel size of every image under public/media, used to set
// width/height on <img> so the browser can reserve space (no CLS).

export const IMAGE_DIMS: Record<string, { width: number; height: number }> = {
${lines.join('\n')}
};

export function dims(src: string): { width: number; height: number } | undefined {
  return IMAGE_DIMS[src];
}
`;

fs.writeFileSync(path.join(root, 'src/content/image-dims.ts'), out, 'utf8');
console.log(`wrote ${entries.length} entries`);
